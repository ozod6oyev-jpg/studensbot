/**
 * Student Daftari — matematik va yunon belgilarining "qalam" kutubxonasi.
 *
 * Har bir belgi em-qutisida yozilgan qalam harakatlaridan iborat:
 *   x: 0 (belgi boshi) → advance (belgi oxiri)
 *   y: 0 — asosiy chiziq (baseline), musbat qiymat yuqoriga
 * Kichik harflar balandligi ≈ 0.5, katta harflar ≈ 0.7.
 */
import type { StrokePoint, StrokePath, SymbolDef } from "./types";

type P = [number, number];

/** Nuqtalar ro'yxatidan qalam harakati yasaydi. */
const poly = (points: P[], width?: number): StrokePath => ({
  points: points.map(([x, y]): StrokePoint => ({ x, y })),
  ...(width === undefined ? {} : { width }),
});

/** Ikki nuqta orasidagi to'g'ri chiziq. */
const seg = (x1: number, y1: number, x2: number, y2: number, width?: number): StrokePath =>
  poly(
    [
      [x1, y1],
      [x2, y2],
    ],
    width,
  );

const circlePoints = (cx: number, cy: number, r: number, steps: number): P[] =>
  Array.from({ length: steps }, (_, i) => {
    const a = (i / steps) * Math.PI * 2;
    return [cx + r * Math.cos(a), cy + r * Math.sin(a)] as P;
  });

/** Yopiq aylana (masalan `∅`, `⊕`). */
const ring = (cx: number, cy: number, r: number, width = 0.07, steps = 12): StrokePath => ({
  points: circlePoints(cx, cy, r, steps).map(([x, y]): StrokePoint => ({ x, y })),
  closed: true,
  width,
});

/** Qalin nuqta (masalan `·`, `∴`). */
const dot = (cx: number, cy: number, width = 0.1): StrokePath => ring(cx, cy, 0.035, width, 8);

/** Burchak bo'ylab yoy nuqtalari (gradusda, 0° — o'ngga, soat miliga teskari). */
const arcPoints = (
  cx: number,
  cy: number,
  r: number,
  from: number,
  to: number,
  steps: number,
  ry?: number,
): P[] => {
  const ratio = ry ?? r;
  return Array.from({ length: steps + 1 }, (_, i) => {
    const a = ((from + ((to - from) * i) / steps) * Math.PI) / 180;
    return [cx + r * Math.cos(a), cy + ratio * Math.sin(a)] as P;
  });
};

/** Yoy chizig'i. */
const arc = (
  cx: number,
  cy: number,
  r: number,
  from: number,
  to: number,
  steps = 8,
  width = 0.07,
  ry?: number,
): StrokePath => poly(arcPoints(cx, cy, r, from, to, steps, ry), width);

/** Yopiq oval (masalan `θ`, `φ`, `Θ`). */
const oval = (cx: number, cy: number, rx: number, ry: number, width = 0.07, steps = 16): StrokePath => ({
  points: arcPoints(cx, cy, rx, 0, 360, steps, ry).map(([x, y]): StrokePoint => ({ x, y })),
  closed: true,
  width,
});

/** Qalam harakatini surish (takrorlanuvchi shakllar uchun). */
const shift = (stroke: StrokePath, dx: number, dy = 0): StrokePath => ({
  ...stroke,
  points: stroke.points.map((p): StrokePoint => ({ x: p.x + dx, y: p.y + dy })),
});

/** Belgini qisqa ko'rinishda yasash. */
const def = (advance: number, ...strokes: StrokePath[]): SymbolDef => ({ advance, strokes });

